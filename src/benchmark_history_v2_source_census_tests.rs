#[test]
fn semantic_coverage_excludes_only_committed_generated_and_vendored_evidence() {
    for path in [
        "aci/e2e/aci-demo/web/static/angular.min.js",
        "public/runtime.min.mjs",
        "assets/vendor.min.cjs",
    ] {
        assert_eq!(
            source_semantic_coverage(path, b"function compact(){return 1}"),
            HistoricalV2SourceSemanticCoverage::GeneratedPath,
            "{path}"
        );
    }
    assert_eq!(
        source_semantic_coverage(
            "src/client.js",
            b"// Code generated by tool. DO NOT EDIT.\n"
        ),
        HistoricalV2SourceSemanticCoverage::GeneratedHeader
    );
    assert_eq!(
        source_semantic_coverage("third_party/client.js", b"export function run() {}\n"),
        HistoricalV2SourceSemanticCoverage::VendoredPath
    );
    for path in ["src/admin.js", "src/minimal.js", "src/client.js"] {
        assert_eq!(
            source_semantic_coverage(path, b"export function run() {}\n"),
            HistoricalV2SourceSemanticCoverage::Required,
            "{path}"
        );
    }
    assert_eq!(
        source_semantic_coverage(
            "src/detector.rs",
            b"const MARKER: &str = \"code generated by\";\n"
        ),
        HistoricalV2SourceSemanticCoverage::Required
    );
}

#[test]
fn commits_complete_base_and_patched_source_snapshots_deterministically() {
    let fixture = Fixture::new();
    let first = fixture.materialize("first");
    let second = fixture.materialize("second");
    let first_census = census_historical_v2_sources(&first.0, &first.1).unwrap();
    let second_census = census_historical_v2_sources(&second.0, &second.1).unwrap();

    assert_eq!(first_census, second_census);
    assert_eq!(first_census.base.tracked_entry_count, 2);
    assert_eq!(first_census.base.source_file_count, 2);
    assert_eq!(first_census.base.method_count, 2);
    assert_eq!(first_census.patched.method_count, 2);
    assert_eq!(
        first_census.base.method_counts_by_language,
        BTreeMap::from([("rust".to_string(), 2)])
    );
    assert_eq!(source_lines(&first_census.base, "src/lib.rs"), 4);
    assert_eq!(source_lines(&first_census.patched, "src/lib.rs"), 3);
    assert_ne!(
        source_hash(&first_census.base, "src/lib.rs"),
        source_hash(&first_census.patched, "src/lib.rs")
    );
    assert_eq!(
        source_hash(&first_census.base, "tests/value.rs"),
        source_hash(&first_census.patched, "tests/value.rs")
    );
    validate_historical_v2_source_census(&first.0, &first.1, &first_census).unwrap();
}

#[test]
fn committed_census_accepts_clean_ident_filtered_worktrees() {
    let source = tempfile::tempdir().unwrap();
    git_ok(source.path(), &["init", "-b", "main"]);
    git_ok(
        source.path(),
        &["config", "user.email", "fixture@example.test"],
    );
    git_ok(source.path(), &["config", "user.name", "Fixture"]);
    fs::create_dir_all(source.path().join("src")).unwrap();
    fs::write(source.path().join(".gitattributes"), "*.rs ident\n").unwrap();
    fs::write(
        source.path().join("src/version.rs"),
        "// $Id$\npub fn version() -> u8 { 1 }\n",
    )
    .unwrap();
    fs::write(
        source.path().join("src/lib.rs"),
        "pub fn value() -> u8 {\n    let value = 1;\n    value\n}\n",
    )
    .unwrap();
    git_ok(source.path(), &["add", "."]);
    git_ok(source.path(), &["commit", "-m", "base"]);
    let base_revision = git_text(source.path(), &["rev-parse", "HEAD"]);
    fs::write(
        source.path().join("src/lib.rs"),
        "pub fn value() -> u8 {\n    1\n}\n",
    )
    .unwrap();
    let historical_patch = git_text(source.path(), &["diff", "--binary", "HEAD"]) + "\n";
    git_ok(source.path(), &["reset", "--hard", "HEAD"]);

    let parent = tempfile::tempdir().unwrap();
    let materialized = super::super::history_v2_materialization::materialize_from_url(
        "example/repo",
        &source.path().to_string_lossy(),
        &base_revision,
        &historical_patch,
        &sha256(historical_patch.as_bytes()),
        &parent.path().join("ident"),
    )
    .unwrap();
    git_ok(
        &materialized.1.repository_root,
        &[
            "remote",
            "set-url",
            "origin",
            "https://github.com/example/repo.git",
        ],
    );

    let version_path = materialized.1.base_root.join("src/version.rs");
    let object_id = git_text(
        &materialized.1.base_root,
        &["rev-parse", "HEAD:src/version.rs"],
    );
    let committed = git_bytes(&materialized.1.base_root, &["cat-file", "blob", &object_id]);
    let worktree = fs::read(&version_path).unwrap();
    assert_ne!(worktree, committed);
    assert!(String::from_utf8(worktree).unwrap().contains("$Id:"));
    assert!(
        git_text(
            &materialized.1.base_root,
            &["status", "--porcelain=v1", "--untracked-files=all"]
        )
        .is_empty()
    );

    let census = census_historical_v2_sources(&materialized.0, &materialized.1).unwrap();
    assert_eq!(
        source_hash(&census.base, "src/version.rs"),
        sha256(&committed)
    );
    assert_eq!(
        source_hash(&census.patched, "src/version.rs"),
        sha256(&committed)
    );
    validate_historical_v2_source_census(&materialized.0, &materialized.1, &census).unwrap();
}

