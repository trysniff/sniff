use super::exact_generator_marker;

#[test]
fn go_marker_must_precede_code_and_start_at_column_zero() {
    let valid = "// license\n\n// Code generated by stringer. DO NOT EDIT.\npackage sample\n";
    let marker = exact_generator_marker("sample.go", valid).expect("canonical marker");
    assert_eq!(marker.start_line_zero_based, 2);
    assert_eq!(marker.start_character_zero_based, 0);

    let indented = "  // Code generated by stringer. DO NOT EDIT.\npackage sample\n";
    assert!(exact_generator_marker("sample.go", indented).is_none());

    let after_code = "package sample\n// Code generated by stringer. DO NOT EDIT.\n";
    assert!(exact_generator_marker("sample.go", after_code).is_none());
}

#[test]
fn go_marker_is_not_limited_to_the_first_twenty_lines() {
    let source = format!(
        "{}// Code generated by protoc. DO NOT EDIT.\npackage sample\n",
        "// license\n".repeat(24)
    );

    let marker = exact_generator_marker("sample.go", &source).expect("canonical marker");

    assert_eq!(marker.start_line_zero_based, 24);
}

#[test]
fn go_marker_can_follow_only_comment_forms() {
    let source = concat!(
        "/* license\n",
        "continued */ // trailing comment\n",
        "// Code generated by tool. DO NOT EDIT.\r\n",
        "package sample\r\n",
    );

    assert!(exact_generator_marker("sample.go", source).is_some());
}

#[test]
fn non_go_generated_marker_contract_is_unchanged() {
    let marker = exact_generator_marker("sample.rs", "  // @generated\npub fn run() {}")
        .expect("cross-language marker");

    assert_eq!(marker.start_character_zero_based, 2);
}
